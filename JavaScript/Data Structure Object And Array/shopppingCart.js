//Create an array of shopping items, Add one new item, Remove the last item, Print the final array.
//concepts: arrays(), push(), pop()
let shoppingItem = ["milk","butter","bread","jam"];
console.log(shoppingItem);
//adding new item
shoppingItem.push("sugar");
console.log(shoppingItem);
//removing
shoppingItem.pop();
console.log(shoppingItem);
delete shoppingItem[0];
console.log(shoppingItem);
shoppingItem[0] = "GreenTea";
console.log(shoppingItem);



